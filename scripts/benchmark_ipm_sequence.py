def _workspace_identity(solver):
    """Host metadata only: no device synchronization or array downloads."""
    factor = solver.factor
    handle = getattr(factor, 'objects', {}).get('handle')
    def pointer(value):
        return getattr(getattr(value, 'data', None), 'ptr', None)
    return dict(solver_object_id=id(solver), factor_object_id=id(factor),
        native_handle_value=getattr(handle, 'value', None),
        factor_values_pointer=pointer(getattr(factor, 'values', None)),
        solver_values_pointer=pointer(getattr(solver, 'values', None)),
        factor_rhs_pointer=pointer(getattr(factor, 'rhs', None)),
        factor_solution_pointer=pointer(getattr(factor, 'solution', None)))


class _GpuSequenceWorkspace:
    """One live solver, with explicit close on every return/exception path."""

    def __init__(self, factory, options, *, reuse, rebind):
        self.factory, self.options = factory, options
        self.reuse, self.rebind = reuse, rebind
        self.solver = self._owner = None
        self.created = self.closed = self.update_attempts = self.update_successes = self.rejections = 0
        self.analysis_total = self._analysis_seen = 0

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()

    def observe_analysis(self):
        if self.solver is not None:
            count = int(self.solver.factor.analysis_count)
            if count < self._analysis_seen:
                raise RuntimeError('Symbolic analysis counter decreased within one workspace')
            self.analysis_total += count - self._analysis_seen
            self._analysis_seen = count
        return self.analysis_total

    def close(self):
        started = time.perf_counter()
        if self._owner is not None:
            owner, self._owner = self._owner, None
            try:
                self.observe_analysis()
            finally:
                self.solver = None
                try:
                    owner.close()
                finally:
                    self.closed += 1
        return time.perf_counter() - started

    def prepare(self, problems):
        metadata = dict(workspace_created=False, workspace_rebuilt=False,
            constructor_seconds=0., replaced_workspace_close_seconds=0.,
            numeric_update_attempted=False, numeric_update_succeeded=False,
            numeric_update_wall_seconds=0., numeric_update=None,
            numeric_update_rejected=None, previous_workspace_identity=None,
            native_workspace_identity_preserved=None)
        if self.solver is not None:
            if not self.reuse:
                raise RuntimeError('Non-reusing mode must close each previous step')
            old_identity = _workspace_identity(self.solver)
            metadata['previous_workspace_identity'] = old_identity
            metadata['symbolic_analysis_count_before_update'] = int(self.solver.factor.analysis_count)
            metadata['numeric_update_attempted'] = True
            self.update_attempts += 1
            stamp = time.perf_counter()
            try:
                metadata['numeric_update'] = self.rebind(self.solver, problems)
            except NumericRebindRejected as error:
                # Only an explicitly rejected update is allowed to use fresh
                # GPU construction. Native/runtime errors propagate and close.
                metadata['numeric_update_rejected'] = str(error)
                self.rejections += 1
            else:
                new_identity = _workspace_identity(self.solver)
                same = {key: value == new_identity[key] for key, value in old_identity.items()}
                metadata['native_workspace_identity_preserved'] = same
                if not all(same.values()):
                    raise RuntimeError('Numeric rebind replaced a native workspace object or buffer')
                metadata['numeric_update_succeeded'] = True
                self.update_successes += 1
                self.observe_analysis()
            finally:
                metadata['numeric_update_wall_seconds'] = time.perf_counter() - stamp
            if not metadata['numeric_update_succeeded']:
                metadata['replaced_workspace_close_seconds'] = self.close()
        if self.solver is None:
            stamp = time.perf_counter()
            # The concrete factory is responsible for failed-constructor
            # cleanup. Once it returns, register close before exposing it.
            with ExitStack() as pending:
                solver = self.factory(problems, **self.options)
                pending.callback(solver.close)
                identity = _workspace_identity(solver)
                analysis = int(solver.factor.analysis_count)
                self._owner = pending.pop_all()
            self.solver = solver
            metadata['workspace_rebuilt'] = self.created > 0
            self.created += 1
            metadata['workspace_created'] = True
            metadata['constructor_seconds'] = time.perf_counter() - stamp
            self._analysis_seen = analysis
            self.analysis_total += analysis
        else:
            identity = _workspace_identity(self.solver)
        metadata.update(workspace_generation=self.created, workspace_identity=identity,
            symbolic_analysis_count_after_prepare=int(self.solver.factor.analysis_count),
            cumulative_symbolic_analysis_count=self.observe_analysis(),
            cumulative_workspace_creations=self.created,
            cumulative_workspace_rebuilds=max(0, self.created-1))
        return self.solver, metadata


def _run_gpu_sequence(record, args, inputs, *, cp, solver_factory, rebind_workspace):
    def update_workspace(solver, problems):
        if getattr(args,'device_numeric_updates',False):
            return solver._device_numeric_plan.rebind(problems)
        options = {}
        if getattr(args, 'reuse_static_forest', False): options['reuse_static_forest'] = True
        if getattr(args, 'device_staging', False): options['device_staging'] = True
        if getattr(args, 'direct_kkt_payload', False): options['direct_kkt_payload'] = True
        return rebind_workspace(solver, problems, **options)
    def make_solver(problems, **options):
        solver=solver_factory(problems,**options)
        if getattr(args,'device_numeric_updates',False):
            try:
                from src.gpu_ipm_device_update import DeviceNumericUpdatePlan
                solver._device_numeric_plan=DeviceNumericUpdatePlan(solver)
            except BaseException:
                solver.close()
                raise
        return solver
    options = dict(regularization=getattr(args,'newton_regularization',1e-6), globalized=True,
        krylov_coordinates=getattr(args,'krylov_coordinates','full'),
        fused_solve_guards=getattr(args,'fused_solve_guards',False),
        factor_layout=getattr(args,'factor_layout','uniform'),
        factor_ordering=getattr(args,'factor_ordering','default'),
        factor_algorithm=getattr(args,'factor_algorithm','default'),
        factor_precision=getattr(args,'factor_precision','float64'),
        reuse_equality_proofs=getattr(args,'reuse_equality_proofs',False),
        newton_backend=getattr(args,'newton_backend','augmented'),
        centrality_corrections=getattr(args,'centrality_corrections',0),
        step_policy=getattr(args,'step_policy','common'),
        shared_factor_group_size=getattr(args,'shared_factor_group_size',1),
        forcing_eta=.1, regularization_retries=1, newton_krylov_iterations=16,
        predictor_corrector=True, predictor_affine_fraction=.995,
        ipm_initialization='balanced', exact_equalities=True, allow_box_dual=True,
        second_forest=args.second_forest, fix_singleton_equalities=args.fix_singleton_equalities,
        device_checked_solves=True, factor_refinements=0, krylov_microkernels='all',
        krylov_defer_lane_checks=True, reuse_gmres_workspace=args.reuse_gmres_workspace,
        retain_internal_state=args.warm)
    previous = None
    record['cpu_lp_calls'] = 0
    record['gpu_workspace_policy'] = ('compatible_numeric_rebind_else_fresh_GPU' if
        args.reuse_numeric_workspace else 'fresh_GPU_workspace_each_step')
    with _GpuSequenceWorkspace(make_solver, options, reuse=args.reuse_numeric_workspace,
                               rebind=update_workspace) as workspace:
        for index, (step, (problems, provenance)) in enumerate(zip(args.steps, inputs)):
            step_start = time.perf_counter()
            trial = dict(step=step, problem_sha256=provenance['problem_sha256'])
            solver, metadata = workspace.prepare(problems)
            trial.update(metadata)
            if tuple(solver.problem_hashes) != tuple(provenance['problem_sha256']):
                raise RuntimeError('Prepared GPU workspace does not contain the CURRENT original LP inputs')
            bound = None
            stamp = time.perf_counter()
            if previous is not None:
                try:
                    # previous is an exported bundle from the preceding step;
                    # rebind clears old internal state before this NEW bind.
                    bound = previous.bind(solver, environment_ids=list(range(args.batch)),
                        stage=args.stage, step=step, interior_floor=args.interior_floor,
                        repair_slacks=args.repair_slacks, restart_mu=getattr(args, 'restart_mu', None))
                except ValueError as error:
                    trial['warm_binding_rejected'] = str(error)
            trial['binding_seconds'] = time.perf_counter()-stamp
            solve_options={}
            if bound is not None and getattr(args,'factor_reuse_interval',1)>1:
                solve_options['factor_reuse_interval']=args.factor_reuse_interval
            result = solver.solve(iterations=args.iterations, internal_warm_start=bound,**solve_options)
            trial['solve_api_seconds'] = result['total_seconds']
            stamp = time.perf_counter()
            x, y = result['x'].get(), result['y'].get()
            certificates = [paired_certificate(p, xx, yy) for p,xx,yy in zip(problems,x,y)]
            direct_rows = [{k:np.asarray(v).tolist() for k,v in audit_direct_dual(p,xx,yy,xp=np).items()}
                for p,xx,yy in zip(problems,x,y)]
            require_direct = args.second_forest or args.fix_singleton_equalities
            qualified = bool(result['accepted'].all() and all(r['certificate_passed'] for r in certificates)
                and (not require_direct or all(_independent_direct_gate(v) for v in direct_rows)))
            trial['all_original_certificates_passed'] = qualified
            trial['independent_host_certificates'] = certificates
            trial['independent_direct_dual_audits'] = direct_rows
            trial['D2H_and_independent_verification_seconds'] = time.perf_counter()-stamp
            stamp = time.perf_counter()
            previous = (solver.export_internal_state(environment_ids=list(range(args.batch)),
                stage=args.stage, step=step) if args.warm and qualified else None)
            trial['export_recertification_and_snapshot_seconds'] = time.perf_counter()-stamp
            trial['symbolic_analysis_count_after_solve'] = int(solver.factor.analysis_count)
            trial['cumulative_symbolic_analysis_count'] = workspace.observe_analysis()
            trial['workspace_identity_after_solve'] = _workspace_identity(solver)
            for key in tuple(result):
                if isinstance(result[key], cp.ndarray): result.pop(key)
            trial['solver_result'] = result
            trial['step_end_workspace_close_seconds'] = 0.
            if not args.reuse_numeric_workspace or not qualified or index == len(args.steps)-1:
                trial['step_end_workspace_close_seconds'] = workspace.close()
            trial['full_step_lifecycle_seconds'] = time.perf_counter()-step_start
            record['steps'].append(trial)
            print(json.dumps(dict(step=step, seconds=trial['solve_api_seconds'],
                full_step_seconds=trial['full_step_lifecycle_seconds'], qualified=qualified,
                warm=bound is not None, workspace_created=trial['workspace_created'],
                numeric_update=trial['numeric_update_succeeded'], factor_count=result['factor_count'])), flush=True)
            if not qualified: break
    record.update(GPU_workspace_rebuilt_each_step=bool(record['steps']) and all(
        trial['workspace_created'] for trial in record['steps']),
        gpu_workspace_creations=workspace.created, gpu_workspace_rebuilds=max(0, workspace.created-1),
        gpu_workspace_close_calls=workspace.closed, numeric_update_attempts=workspace.update_attempts,
        numeric_update_successes=workspace.update_successes, numeric_update_rejections=workspace.rejections,
        actual_symbolic_analysis_count=workspace.analysis_total)


def validate_sequence_provenance(provenances, steps, stage, batch, manifest_raw):
    """One immutable trace identity and ordered environment list for all steps."""
    manifest = json.loads(manifest_raw)
    digest = hashlib.sha256(manifest_raw).hexdigest()
    if (not steps or steps != list(range(steps[0], steps[-1]+1))
            or len(provenances) != len(steps) or len(manifest['seeds']) < batch
            or len(set(manifest['seeds'][:batch])) != batch):
        raise ValueError('Consecutive steps and distinct recorded environments required')
    directory = provenances[0]['trace_directory']
    for step, provenance in zip(steps, provenances):
        if provenance['input_manifest_sha256'] != digest or provenance['trace_directory'] != directory:
            raise ValueError('Mixed trace manifests or directories cannot establish causal identity')
        entries = provenance['entries']
        if len(entries) != batch or len(provenance['problem_sha256']) != batch:
            raise ValueError('Incomplete ordered input provenance')
        for environment, entry in enumerate(entries):
            if (entry['environment_id'] != environment or entry['step'] != step or entry['stage'] != stage
                    or entry['problem_sha256'] != provenance['problem_sha256'][environment]):
                raise ValueError('Environment, stage, step or original problem hash mismatch')
    return dict(input_manifest_sha256=digest, ordered_environment_ids=list(range(batch)),
                ordered_environment_seeds=manifest['seeds'][:batch], trace_directory=directory)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--trace', type=Path, default=ROOT/'results/pf_lp_trace_dev32x41_20260905')
    parser.add_argument('--mode', choices=['cpu', 'gpu'], required=True)
    parser.add_argument('--stage', choices=['maxmin', 'aggregate', 'exchange'], default='maxmin')
    parser.add_argument('--steps', type=int, nargs='+', default=[2, 3, 4])
    parser.add_argument('--batch', type=int, choices=[1, 2, 4, 8, 16, 32], default=32)
    parser.add_argument('--workers', type=int, choices=[1, 2, 4, 8, 10, 16], default=16)
    parser.add_argument('--warm', action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument('--interior-floor', type=float, default=0.)
    parser.add_argument('--repair-slacks', action='store_true')
    parser.add_argument('--restart-mu', type=float, default=None,
        help='Experimental current-bound dual restart; replaces old y/z/s, never LP bounds or precision')
    parser.add_argument('--iterations', type=int, default=240)
    parser.add_argument('--factor-reuse-interval',type=int,choices=range(1,9),default=1,
        help='Experimental within-solve factor lag on warm GPU steps only; current full Newton forcing is checked')
    parser.add_argument('--krylov-coordinates',choices=['full','condensed'],default='full')
    parser.add_argument('--fused-solve-guards',action='store_true')
    parser.add_argument('--factor-layout',choices=['uniform','block_diagonal'],default='uniform')
    parser.add_argument('--factor-ordering',choices=['default','amd'],default='default')
    parser.add_argument('--factor-algorithm',choices=['default','alternate'],default='default')
    parser.add_argument('--factor-precision',choices=['float64','float32'],default='float64')
    parser.add_argument('--reuse-equality-proofs',action='store_true')
    parser.add_argument('--newton-backend',choices=['augmented','dual_schur'],default='augmented')
    parser.add_argument('--centrality-corrections',type=int,choices=range(5),default=0)
    parser.add_argument('--step-policy',choices=['common','primal_dual'],default='common')
    parser.add_argument('--shared-factor-group-size',type=int,choices=[1,2,4,8,16,32],default=1)
    parser.add_argument('--newton-regularization',type=float,default=1e-6,
        help='Preconditioner only; original unregularized Newton/LP tests remain mandatory')
    parser.add_argument('--second-forest', action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument('--fix-singleton-equalities', action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument('--reuse-gmres-workspace', action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument('--reuse-numeric-workspace', action=argparse.BooleanOptionalAction, default=False,
        help='Opt-in compatible GPU numeric rebind; rejected topology uses explicitly timed fresh GPU setup')
    parser.add_argument('--reuse-static-forest', action='store_true')
    parser.add_argument('--device-staging', action='store_true')
    parser.add_argument('--direct-kkt-payload', action='store_true')
    parser.add_argument('--device-numeric-updates',action='store_true',
        help='Fixed-layout reductions and numeric payload updates on CUDA; host input pack/hash remain timed')
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    if args.factor_reuse_interval>1 and (args.mode!='gpu' or args.krylov_coordinates!='condensed'):
        raise ValueError('Factor lag requires GPU mode and condensed Krylov coordinates')
    if args.mode!='gpu' and (args.factor_layout!='uniform' or args.fused_solve_guards
                           or args.factor_ordering!='default' or args.factor_algorithm!='default'
                           or args.factor_precision!='float64' or args.newton_regularization!=1e-6
                           or args.reuse_equality_proofs or args.newton_backend!='augmented'
                           or args.centrality_corrections or args.step_policy!='common' or args.shared_factor_group_size!=1):
        raise ValueError('GPU execution options cannot describe a CPU trial')
    if args.output.exists(): raise FileExistsError('Never overwrite previous measurements')
    if (args.reuse_static_forest or args.device_staging or args.direct_kkt_payload) and not args.reuse_numeric_workspace:
        raise ValueError('Numeric update optimizations require --reuse-numeric-workspace')
    if args.device_numeric_updates and (not args.reuse_numeric_workspace
            or args.reuse_static_forest or args.device_staging or args.direct_kkt_payload):
        raise ValueError('Device numeric update requires reuse-numeric-workspace and replaces other host-update options')
    if args.restart_mu is not None and (not np.isfinite(args.restart_mu)
            or not 1e-8 <= args.restart_mu <= 1e-2 or args.repair_slacks or args.interior_floor != 0.):
        raise ValueError('restart-mu must be 1e-8..1e-2 and separate from floor/slack-repair modes')
    if (not args.steps or min(args.steps) < 0 or args.steps != list(range(args.steps[0], args.steps[-1]+1))
            or args.iterations < 0 or not np.isfinite(args.interior_floor) or not 0. <= args.interior_floor <= 1e-2):
        raise ValueError('Consecutive steps, nonnegative iterations and bounded interior floor required')
    stamp = time.perf_counter()
    inputs = [load_inputs(args.trace, args.stage, step, args.batch) for step in args.steps]
    manifest_raw = (args.trace/'manifest.json').read_bytes()
    sequence_identity = validate_sequence_provenance([p for _,p in inputs], args.steps,
        args.stage, args.batch, manifest_raw)
    n_fluxes = None
    if args.mode == 'cpu':
        # Flux-dimension validation is input preparation, not CPU solve time.
        maxmin, provenance = (inputs[0] if args.stage == 'maxmin' else
            load_inputs(args.trace, 'maxmin', args.steps[0], args.batch))
        validate_sequence_provenance([provenance], [args.steps[0]], 'maxmin', args.batch, manifest_raw)
        n_fluxes = maxmin[0][4].size - 1
        if any(np.flatnonzero(p[4]).tolist() != [n_fluxes] for p in maxmin):
            raise ValueError('Cannot establish the trace community flux dimension')
    input_load_seconds = time.perf_counter()-stamp
    record = dict(role='changing_saved_input_stage_reoptimization_NOT_closed_loop_dfba_or_PPO',
        configuration={k:str(v) if isinstance(v, Path) else v for k,v in vars(args).items()},
        input_load_seconds=input_load_seconds, sequence_identity=sequence_identity,
        input_provenance=[p for _,p in inputs], current_reference_vectors_loaded=False,
        current_CPU_solutions_passed_to_GPU=False, steps=[], completed=False,
        original_certificate_limits=dict(primal_residual=1e-5, dual_violation=1e-7, relative_kkt_gap=1e-7))
    source_paths = ['scripts/benchmark_ipm_sequence.py', 'scripts/benchmark_ipm_cpu_inputs.py',
        'src/gpu_ipm_warm_state.py', 'src/gpu_ipm_numeric_update.py', 'src/gpu_ipm_reoptimization.py',
        'src/gpu_ipm_staging.py', 'src/gpu_ipm_kkt_payload.py', 'src/csr_block_assembly.py',
        'src/gpu_lp_numeric.py','src/gpu_ipm_device_update.py','src/gpu_ipm_device_payload.py',
        'src/gpu_forest_numeric_bounds.py','src/gpu_segmented_linear.py','src/gpu_solve_guards.py',
        'src/gpu_batched_ipm.py', 'src/gpu_condensed_ipm.py',
        'src/gpu_globalized_ipm.py', 'src/gpu_globalized_condensed.py', 'src/gpu_newton_krylov.py',
        'src/gpu_zero_face_ipm.py', 'src/gpu_forest_ipm.py', 'src/gpu_forest_map.py',
        'src/lp_zero_face.py', 'src/lp_equality_reduction.py', 'src/lp_exact_equalities.py',
        'src/gpu_sparse_factor.py', 'src/gpu_dual_schur.py','src/gpu_centrality_corrector.py','src/gpu_shared_newton.py', 'src/gpu_block_lp.py', 'src/gpu_ipm_initialization.py',
        'src/gpu_krylov_microkernels.py', 'src/cpu_repeated_lp.py']
    record['source_snapshots'] = {p:(ROOT/p).read_text() for p in source_paths}
    record['source_sha256'] = {p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in source_paths}
    sequence_start = time.perf_counter()
    if args.mode == 'cpu':
        from src.cpu_repeated_lp import RepeatedCpuLP
        record['highspy_version'] = version('highspy')
        record['gpu_calls'] = 0
        with closing(RepeatedCpuLP(workers=args.workers, reuse_basis=args.warm, n_fluxes=n_fluxes,
                                   exchange_support_updates=True)) as service:
            for step, (problems, provenance) in zip(args.steps, inputs):
                trial = _timed_batch(service, problems, [problem_request(p, stage=args.stage) for p in problems],
                    args.stage, 'changing_saved_input', step,
                    require_direct_dual=bool(args.second_forest or args.fix_singleton_equalities))
                record['steps'].append(dict(step=step, problem_sha256=provenance['problem_sha256'], **trial))
                print(json.dumps(dict(step=step, seconds=trial['solve_batch_wall_seconds'],
                    qualified=trial['all_original_certificates_passed'])), flush=True)
                if not trial['all_original_certificates_passed']: break
            record.update(history_counts(service.history))
    else:
        import cupy as cp
        from src.gpu_forest_ipm import ForestGpuBatchedIPM
        from src.gpu_ipm_numeric_update import rebind_forest_ipm
        record['device'] = cp.cuda.runtime.getDeviceProperties(0)['name'].decode()
        _run_gpu_sequence(record, args, inputs, cp=cp, solver_factory=ForestGpuBatchedIPM,
                          rebind_workspace=rebind_forest_ipm)
    record['sequence_lifecycle_seconds'] = time.perf_counter()-sequence_start
    record['all_requested_steps_qualified'] = (len(record['steps']) == len(args.steps)
        and all(s['all_original_certificates_passed'] for s in record['steps']))
    record['completed'] = True
    serialized = json.dumps(_json_safe(record), indent=2, allow_nan=False)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open('x', encoding='utf-8') as output: output.write(serialized)
    print('Saved '+str(args.output), flush=True)


if __name__ == '__main__': main()
